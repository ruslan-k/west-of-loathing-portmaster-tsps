#!/usr/bin/env python3
"""Generate the ASTC payload header used by tools/wol_astc_probe.c.

Usage:
  python3 tools/wol_astc_probe_gen.py --input probe-input.png --block 6x6 \
      --out-header astc_data.h [--astcenc 'astcenc'|'docker exec astc-tool astcenc']

Runs the ASTC encoder, strips the 16-byte file header and writes the raw block stream
as a C array. Verified format notes (Mali blob v1.r32p0, 2026-10-16):
  - the GL enum for ASTC 6x6 is 0x93B4; 0x93B0 is 4x4 (probe.c uses the right one),
  - imageSize for glCompressedTexImage2D must be exactly ceil(w/bx)*ceil(h/by)*16;
    the driver returns GL_INVALID_VALUE on any mismatch, which is a useful sanity gate.
"""
from pathlib import Path
import argparse
import struct
import subprocess
import sys


def main():
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument('--input', type=Path, required=True, help='source PNG (RGBA)')
    ap.add_argument('--block', default='6x6', help='ASTC block, e.g. 6x6')
    ap.add_argument('--out-header', type=Path, required=True)
    ap.add_argument('--astcenc', default='astcenc', help="encoder command prefix, or 'docker exec astc-tool astcenc'")
    ap.add_argument('--array', default=None, help='C array name (default: astc_<bx>x<by>_data)')
    a = ap.parse_args()

    bx, by = (int(v) for v in a.block.split('x'))
    array = a.array or f'astc_{bx}x{by}_data'
    tmp = a.out_header.with_suffix('.astc')
    cmd = a.astcenc.split() + ['-cl', str(a.input), str(tmp), a.block, '-medium']
    r = subprocess.run(cmd, capture_output=True, text=True)
    if r.returncode != 0:
        print(r.stdout, r.stderr, file=sys.stderr)
        raise SystemExit('astcenc failed')

    raw = tmp.read_bytes()
    assert raw[:4] == bytes([0x13, 0xAB, 0xA1, 0x5C]), 'not an ASTC file'
    assert raw[4] == bx and raw[5] == by and raw[6] == 1, 'block size mismatch'

    def u24(o):
        return raw[o] | (raw[o + 1] << 8) | (raw[o + 2] << 16)

    dx, dy, dz = u24(7), u24(10), u24(13)
    blocks = ((dx + bx - 1) // bx) * ((dy + by - 1) // by) * ((dz + 1 - 1) // 1)
    data = raw[16:]
    assert len(data) == blocks * 16, f'payload {len(data)} != expected {blocks * 16}'

    lines = [f'/* generated by tools/wol_astc_probe_gen.py from {a.input.name}; '
             f'{dx}x{dy} ASTC {a.block}, {len(data)} bytes */',
             f'static const unsigned char {array}[{len(data)}]={{']
    for i in range(0, len(data), 24):
        lines.append(','.join(str(b) for b in data[i:i + 24]) + ',')
    lines.append('};')
    a.out_header.write_text('\n'.join(lines) + '\n')
    print(f'WROTE {a.out_header} dims={dx}x{dy} block={a.block} bytes={len(data)}')
    tmp.unlink(missing_ok=True)


if __name__ == '__main__':
    main()
